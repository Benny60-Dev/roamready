// Build script: regenerate server/src/utils/commonPasswords.ts from the
// canonical SecLists "10-million-password-list-top-10000" file.
//
// USAGE (manual, run when you want to refresh the blocklist):
//   cd server
//   node scripts/build-common-passwords.js
//
// This script does the build-time network fetch. The produced .ts file
// is what ships — the running server never calls out to GitHub.
//
// Design:
//   - Native Node fetch (Node 18+). Zero new npm deps.
//   - Lowercases every entry, trims whitespace, drops empties.
//   - De-dupes via Set while preserving source order (insertion order
//     is significant — SecLists sorts by leak frequency, so the most
//     common entries come first; preserved here for any future
//     diagnostic that wants to look at "top N").
//   - Hard-asserts length >= 9500. The full file is ~10,000 entries;
//     anything substantially smaller means the fetch returned an HTML
//     error page or a truncated body. Fail loudly so a botched refresh
//     never silently weakens the policy.
//   - Writes commonPasswords.ts in the same shape passwordPolicy.ts
//     expects: a const string[] LIST plus the COMMON_PASSWORDS Set
//     export and the COMMON_PASSWORDS_COUNT diagnostic export.

const fs = require('fs')
const path = require('path')

// SecLists renamed the historical "10-million-password-list-top-10000.txt"
// to "10k-most-common.txt" — same provenance (top-10K most-leaked across
// the major public credential dumps), shorter name. The Common-Credentials
// directory listing confirmed this on 2026-05-11. If SecLists rotates the
// path again, just update this constant; the rest of the script doesn't
// hard-code the filename.
const SOURCE_URL =
  'https://raw.githubusercontent.com/danielmiessler/SecLists/master/Passwords/Common-Credentials/10k-most-common.txt'

const OUT_PATH = path.resolve(__dirname, '../src/utils/commonPasswords.ts')

const MIN_EXPECTED_ENTRIES = 9500

;(async () => {
  console.log(`Fetching ${SOURCE_URL} ...`)
  const res = await fetch(SOURCE_URL)
  if (!res.ok) {
    console.error(`Fetch failed: HTTP ${res.status} ${res.statusText}`)
    process.exit(1)
  }
  const body = await res.text()

  // Defense against the failure mode this script's assertion guards
  // against: GitHub serving an HTML error page (rate-limit, 404, etc.)
  // would parse as one long "line" or a handful of tag-shaped lines —
  // either way the length check below catches it, but a fast bail on
  // an obvious HTML preamble keeps the error message tight.
  if (body.trimStart().toLowerCase().startsWith('<!doctype') ||
      body.trimStart().toLowerCase().startsWith('<html')) {
    console.error('Fetch returned HTML, not a password list. Aborting.')
    process.exit(1)
  }

  // Normalize line endings (the file is LF in source but be defensive),
  // lowercase, trim, drop empties. Order-preserving dedupe via Set.
  const rawLines = body.split(/\r?\n/)
  const cleaned = []
  const seen = new Set()
  for (const line of rawLines) {
    const e = line.trim().toLowerCase()
    if (!e) continue
    if (seen.has(e)) continue
    seen.add(e)
    cleaned.push(e)
  }

  console.log(`Parsed ${cleaned.length} unique entries.`)

  if (cleaned.length < MIN_EXPECTED_ENTRIES) {
    console.error(
      `Entry count ${cleaned.length} is below the ${MIN_EXPECTED_ENTRIES} ` +
      `floor — refusing to overwrite commonPasswords.ts. ` +
      `This usually means the fetch returned a partial or error response.`
    )
    process.exit(1)
  }

  // Format entries as a multi-line string[] literal. JSON.stringify
  // handles every escape case (quotes, backslashes, unicode) safely.
  // Eight entries per line keeps the file diffable without being so
  // wide that it forces horizontal scroll.
  const PER_LINE = 8
  const lines = []
  for (let i = 0; i < cleaned.length; i += PER_LINE) {
    const chunk = cleaned.slice(i, i + PER_LINE).map((e) => JSON.stringify(e))
    lines.push('  ' + chunk.join(', ') + ',')
  }

  const fetchedAt = new Date().toISOString()

  const header = `// Common-password blocklist for the password-policy validator
// (server/src/utils/passwordPolicy.ts).
//
// Generated by scripts/build-common-passwords.js — do not hand-edit.
// To refresh: cd server && node scripts/build-common-passwords.js
//
// SOURCE:      ${SOURCE_URL}
// FETCHED:     ${fetchedAt}
// ENTRY COUNT: ${cleaned.length}
//
// The source is the SecLists project's canonical "top 10K" list,
// derived from the largest public credential breaches. Used widely as
// the security industry baseline for breach-list password policy.
//
// Why a Set: O(1) lookup at validation time. Built once at module
// load. Memory cost is negligible (~few hundred KB resident).
//
// Server-side ONLY. NEVER imported under client/ — shipping this in
// the browser bundle would defeat the purpose and bloat the bundle.

`

  const body_ts = `const COMMON_PASSWORDS_LIST: string[] = [
${lines.join('\n')}
]

// Build once at module load. Lowercased entries (the policy validator
// lowercases the input before checking, so the Set must be lowercase
// too — the .map below is defense-in-depth in case a mixed-case
// entry slips in during list maintenance).
export const COMMON_PASSWORDS: Set<string> = new Set(
  COMMON_PASSWORDS_LIST.map(p => p.toLowerCase()),
)

/** Exported for diagnostics / tests — count of entries actually in
 *  the blocklist after dedup. */
export const COMMON_PASSWORDS_COUNT = COMMON_PASSWORDS.size
`

  fs.writeFileSync(OUT_PATH, header + body_ts, 'utf8')

  const sizeKb = (fs.statSync(OUT_PATH).size / 1024).toFixed(1)
  console.log(`Wrote ${OUT_PATH}`)
  console.log(`  entries: ${cleaned.length}`)
  console.log(`  size:    ${sizeKb} KB`)
})().catch((err) => {
  console.error('Unhandled error:', err)
  process.exit(1)
})
